/* Manifesto portfolio atlas · original white portfolio page + October 5 routed tenets.
   Preserve the existing title, three-column introduction, header and footer
   exactly as generated by the canonical renderRoom() in script.js. */
(function () {
  "use strict";
  if(typeof renderRoom!=="function" || typeof state==="undefined") return;
  var TITLES=[
    {zh:"墟语学",en:"Ruin Lexicology",ja:"墟語学"},
    {zh:"近身之物的考古",en:"An Archaeology of Things Close at Hand",ja:"身近なものの考古学"},
    {zh:"借墟",en:"Borrowing the Ruin",ja:"借墟"},
    {zh:"粗野物性",en:"Brutal Materiality",ja:"粗野な物性"},
    {zh:"力流观",en:"The Force-Flow View",ja:"力の流れを観る"},
    {zh:"摧毁试体",en:"The Destructive Test Body",ja:"破壊試験体"},
    {zh:"重返悬境",en:"Return to the Suspended Realm",ja:"懸境へ帰る"},
    {zh:"耗散成声",en:"Dissipation into Sound",ja:"散逸して音となる"},
    {zh:"蓝图成谱",en:"The Blueprint Becomes a Score",ja:"設計図は楽譜となる"},
    {zh:"徒劳之义",en:"The Meaning of Futility",ja:"徒労の意義"}
  ];
  var ORD={
    zh:["第一则","第二则","第三则","第四则","第五则","第六则","第七则","第八则","第九则","第十则"],
    en:["First Tenet","Second Tenet","Third Tenet","Fourth Tenet","Fifth Tenet","Sixth Tenet","Seventh Tenet","Eighth Tenet","Ninth Tenet","Tenth Tenet"],
    ja:["第一則","第二則","第三則","第四則","第五則","第六則","第七則","第八則","第九則","第十則"]
  };
  var TXT={
    zh:{contents:"章节",manifesto:"宣言 / MANIFESTO",prologue:"序言：在建筑之后",modern:"现代废墟",work:"墟构与墟构师",tenets:"墟构师建造十则",selected:"所选章节",read:"阅读完整章节",images:"十则图册"},
    en:{contents:"Contents",manifesto:"MANIFESTO",prologue:"Prologue: After Architecture",modern:"Modern Ruins",work:"Ruinwork and the Ruinwright",tenets:"Tenets of the Ruinwright",selected:"Selected tenet",read:"Read full tenet",images:"Tenet atlas"},
    ja:{contents:"目次",manifesto:"宣言 / MANIFESTO",prologue:"序章――建築のあとで",modern:"現代の廃墟",work:"墟構と墟構師",tenets:"墟構師の建造十則",selected:"選択中の章",read:"本文を読む",images:"十則の図版"}
  };
  var ROOT="https://ruin-archive.site/manifesto.html";
  var prior=renderRoom;
  function lang(){return TXT[state.lang]?state.lang:"zh";}
  function title(item){return item[lang()]||item.zh;}
  function escape(s){return escapeHtml(String(s==null?"":s));}
  function number(n){return String(n).padStart(2,"0");}
  function fullUrl(i){return ROOT+"#section-01-sub-"+number(i);}
  function addition(item){
    var imgs=item.tenetImages||[];
    var t=TXT[lang()], ord=ORD[lang()];
    var cards=TITLES.map(function(name,i){
      return '<button type="button" class="mp-tenet-card" data-mp-tenet="'+i+
        '" aria-pressed="'+(i===0?'true':'false')+'" aria-label="'+escape(ord[i]+'：'+title(name))+'">'+
        '<span class="mp-tenet-ordinal">'+escape(ord[i])+'</span>'+
        '<span class="mp-tenet-tile"><span class="mp-tenet-mat">'+
        '<img src="'+escape(imgs[i]||"")+'" alt="" loading="'+(i<4?"eager":"lazy")+'" decoding="async">'+
        '</span></span>'+
        '<span class="mp-tenet-name">'+escape(title(name))+'</span>'+
      '</button>';
    }).join("");
    function toc(href,code,name,cls){
      return '<a class="'+cls+'" href="'+escape(href)+'" target="_blank" rel="noopener noreferrer">'+
        '<span class="mp-toc-number">'+code+'</span><span>'+escape(name)+'</span></a>';
    }
    var rows=TITLES.map(function(name,i){
      return '<button type="button" class="mp-toc-row'+(i===0?" is-selected":"")+
        '" data-mp-row="'+i+'" aria-label="'+escape(ord[i]+"："+title(name))+'">'+
        '<span class="mp-toc-number">1.2.'+(i+1)+'</span>'+
        '<span>'+escape(ord[i])+'：'+escape(title(name))+'</span></button>';
    }).join("");
    var directory='<aside class="mp-toc" aria-label="'+escape(t.contents)+'">'+
      '<p class="mp-toc-kicker">'+escape(t.contents)+'</p>'+
      '<div class="mp-toc-group">'+
        toc(ROOT+"#section-00","1.1.0",t.prologue,"mp-toc-main")+
        toc(ROOT+"#section-00-sub-00","1.1.1",t.modern,"mp-toc-secondary")+
        toc(ROOT+"#section-00-sub-01","1.1.2",t.work,"mp-toc-secondary")+
        toc(ROOT+"#section-01","1.2.0",t.tenets,"mp-toc-main")+
        rows+
      '</div>'+
    '</aside>';
    var viewer='<section class="mp-preview" data-mp-preview aria-label="'+escape(t.selected)+'">'+
      '<div class="mp-preview-kicker"><span>'+escape(t.selected)+'</span>'+
        '<span data-mp-count>01 / 10</span></div>'+
      '<figure class="mp-preview-figure">'+
        '<img data-mp-image src="'+escape(imgs[0]||"")+'" alt="'+escape(title(TITLES[0]))+'" loading="lazy" decoding="async">'+
        '<figcaption><span data-mp-title>'+escape(ord[0])+'：'+escape(title(TITLES[0]))+'</span>'+
          '<a data-mp-link href="'+escape(fullUrl(0))+'" target="_blank" rel="noopener noreferrer">'+escape(t.read)+' ↗</a>'+
        '</figcaption>'+
      '</figure>'+
    '</section>';
    return '<section class="mp-additions" aria-label="'+escape(t.images)+'">'+
      '<div class="mp-atlas-map" data-mp-map>'+
        '<nav class="mp-tenet-atlas" aria-label="'+escape(t.tenets)+'">'+cards+'</nav>'+
        '<svg class="mp-connectors" data-mp-svg aria-hidden="true"></svg>'+
        '<div class="mp-toc-reading">'+directory+viewer+'</div>'+
      '</div>'+
    '</section>';
  }
  renderRoom=function(item){
    var html=prior(item);
    if(!item || item.slug!=="ruinwright-manifesto")return html;
    var marker=/<section class="writing-tenets" aria-label="Ruinwright ten tenets">[\s\S]*?<\/section>/;
    if(!marker.test(html))return html;
    // Keep the original three-column introduction. The external reading link
    // belongs immediately below its third paragraph, not beneath the atlas.
    var introduction=/<div class="room-intro-stack">([\s\S]*?)<\/div>/;
    var match=html.match(introduction);
    if(match){
      var paragraphs=match[1].match(/<p class="room-intro">[\s\S]*?<\/p>/g);
      if(paragraphs && paragraphs.length===3){
        var visitText=title(item.visitLabel||{zh:"阅读《墟构师宣言》",en:"Read the Manifesto of the Ruinwright",ja:"本文を読む"});
        var link='<a class="mp-intro-visit" href="'+escape(item.visit)+
          '" target="_blank" rel="noopener noreferrer">'+escape(visitText)+' ↗</a>';
        var revised=paragraphs[0]+paragraphs[1]+
          '<div class="mp-intro-final">'+paragraphs[2]+link+'</div>';
        html=html.replace(match[0],'<div class="room-intro-stack">'+revised+'</div>');
      }
    }
    // Remove the two redundant labels while keeping the existing heading and
    // language switch, and delete the old bottom visit/next-work buttons.
    html=html.replace(/(<header class="room-head">[\s\S]*?<p>)[\s\S]*?(<\/p>)/,
      '$1'+escape(title(item.title))+'$2');
    html=html.replace(/<p class="room-group">[\s\S]*?<\/p>/,"");
    html=html.replace(/<div class="room-visit-wrap">[\s\S]*?<\/div>/,"");
    html=html.replace(/<footer class="room-footer">[\s\S]*?<\/footer>/,"");
    return html.replace('class="room-view writing-room"','class="room-view writing-room mp-room"')
      .replace(marker,addition(item));
  };
  // On direct #ruinwright-manifesto reload the script may have already
  // produced the generic page before this renderer was registered.
  if(typeof parseRoute==="function"){
    var route=parseRoute();
    if(route && route.slug==="ruinwright-manifesto")render();
  }

  var current=null,resizeWatcher=null,scheduled=0,chosen=0,hovered=-1;
  var noMotion=!!(window.matchMedia&&window.matchMedia("(prefers-reduced-motion: reduce)").matches);
  function highlight(){
    if(!current)return;
    var selected=hovered>=0?hovered:chosen;
    current.querySelectorAll("[data-mp-tenet]").forEach(function(el){
      var i=Number(el.dataset.mpTenet);
      el.classList.toggle("is-selected",i===selected);
      el.setAttribute("aria-pressed",String(i===chosen));
    });
    current.querySelectorAll("[data-mp-row]").forEach(function(el){
      el.classList.toggle("is-selected",Number(el.dataset.mpRow)===selected);
    });
    current.querySelectorAll(".mp-connector").forEach(function(el){
      el.classList.toggle("is-selected",Number(el.dataset.mpConnector)===selected);
    });
  }
  // A slow, bounded weathering process across the ENTIRE ten-line atlas.
  // Starts at 1–10 randomly placed faults; never exceeds 50 in total.
  // Existing faults mature gradually. No branching or free-standing shards.
  // Restore the original deterministic straight / 45-degree wiring.
  // Fracture animation is suspended until the base geometry is approved.
  function linePath(nodes) {
    return nodes.map(function(p,i) {
      return (i ? "L " : "M ") + p.x.toFixed(2) + " " + p.y.toFixed(2);
    }).join(" ");
  }
  function draw(){
    scheduled=0;
    if(!current||!current.isConnected)return;
    var map=current.querySelector("[data-mp-map]");
    var svg=current.querySelector("[data-mp-svg]");
    var toc=current.querySelector(".mp-toc");
    var atlas=current.querySelector(".mp-tenet-atlas");
    if(!map||!svg||!toc||!atlas)return;
    if(window.matchMedia("(max-width:1199px)").matches){
      svg.replaceChildren();
      return;
    }
    var mr=map.getBoundingClientRect(),tr=toc.getBoundingClientRect();
    var railBottom=atlas.getBoundingClientRect().bottom-mr.top;
    var w=map.clientWidth,h=map.clientHeight;
    if(!w||!h)return;
    svg.setAttribute("viewBox","0 0 "+w+" "+h);
    var cards=Array.from(current.querySelectorAll("[data-mp-tenet]"));
    if(cards.length!==10)return;
    var right=function(i){return cards[i].getBoundingClientRect().right-mr.left-1;};
    // 01–03 from ideal-effect.png: parallel but nonoverlapping channels.
    // Their diagonals all point toward three closely spaced downlegs.
    var base=Math.max(right(0)+49,
      Math.min(tr.right-mr.left+20,right(2)-96));
    var legs=[base,base+17,base+34];
    var sy=railBottom+1,firstOffset=14,secondRise=52;
    var secondAtLane=right(1)+(legs[1]-right(1))*firstOffset/secondRise;
    var firstTurn=Math.max(right(0)+19,Math.min(legs[0]-27,secondAtLane-11));
    var thirdTurn=Math.max(legs[2]+22,right(2)-37);
    var out="";
    cards.forEach(function(card,i){
      var tile=card.querySelector(".mp-tenet-tile");
      var dest=current.querySelector('[data-mp-row="'+i+'"]');
      if(!tile||!dest)return;
      var b=dest.getBoundingClientRect();
      var ex=Math.max(10,b.left-mr.left+4),ey=b.bottom-mr.top+2;
      var nodes;
      if(i===0){
        nodes=[
          {x:right(0),y:sy},
          {x:right(0),y:sy+firstOffset},
          {x:firstTurn,y:sy+firstOffset},
          {x:legs[0],y:sy+54},
          {x:legs[0],y:ey},
          {x:ex,y:ey}
        ];
      }else if(i===1){
        nodes=[
          {x:right(1),y:sy},
          {x:legs[1],y:sy+secondRise},
          {x:legs[1],y:ey},
          {x:ex,y:ey}
        ];
      }else if(i===2){
        nodes=[
          {x:right(2),y:sy},
          {x:thirdTurn,y:sy},
          {x:legs[2],y:sy+70},
          {x:legs[2],y:ey},
          {x:ex,y:ey}
        ];
      }else{
        // 04–10: restore the stable pre-fracture wiring geometry.
        // No extra rightward elbow, no growing fractures.
        var sx=right(i);
        var lane=Math.max(railBottom+9,Math.min(railBottom+18+i*10,ey-80));
        var routeX=tr.right-mr.left+67+i*7;
        var diagonal=25+(i%3)*5;
        nodes=[
          {x:sx,y:sy},
          {x:sx,y:lane},
          {x:routeX,y:lane},
          {x:routeX-diagonal,y:lane+diagonal},
          {x:routeX-diagonal,y:ey},
          {x:ex,y:ey}
        ];
      }
      var d=linePath(nodes);
      out+='<g class="mp-connector" data-mp-connector="'+i+'">'+
        '<path class="mp-connector-main" d="'+d+'"/></g>';
    });
    svg.innerHTML=out;
    highlight();
  }

  function schedule(){
    if(scheduled)cancelAnimationFrame(scheduled);
    scheduled=requestAnimationFrame(draw);
  }
  function choose(i,scroll){
    if(!current||i<0||i>=TITLES.length)return;
    chosen=i;hovered=-1;
    var img=current.querySelector("[data-mp-image]");
    var label=current.querySelector("[data-mp-title]");
    var count=current.querySelector("[data-mp-count]");
    var link=current.querySelector("[data-mp-link]");
    var obj=typeof writings!=="undefined"?writings.find(function(x){return x.slug==="ruinwright-manifesto";}):null;
    if(img&&obj&&obj.tenetImages[i]){img.src=obj.tenetImages[i];img.alt=title(TITLES[i]);}
    if(label)label.textContent=ORD[lang()][i]+"："+title(TITLES[i]);
    if(count)count.textContent=number(i+1)+" / 10";
    if(link)link.href=fullUrl(i);
    highlight();
    if(scroll){
      var focus=current.querySelector(".mp-preview");
      if(focus)focus.scrollIntoView({block:"nearest",behavior:noMotion?"auto":"smooth"});
    }
  }
  function install(){
    var next=document.querySelector(".writing-room.mp-room");
    if(next===current)return;
    if(resizeWatcher){resizeWatcher.disconnect();resizeWatcher=null;}
    current=next;chosen=0;hovered=-1;
    if(!current)return;
    if("ResizeObserver" in window){
      resizeWatcher=new ResizeObserver(schedule);
      resizeWatcher.observe(current.querySelector("[data-mp-map]"));
    }
    current.querySelectorAll(".mp-tenet-tile img").forEach(function(img){
      if(!img.complete)img.addEventListener("load",schedule,{once:true});
    });
    highlight();schedule();
  }
  var app=document.getElementById("app");
  if(app && "MutationObserver" in window)new MutationObserver(install).observe(app,{childList:true,subtree:false});
  window.addEventListener("resize",schedule,{passive:true});
  document.addEventListener("click",function(ev){
    var button=ev.target&&ev.target.closest&&ev.target.closest("[data-mp-tenet],[data-mp-row]");
    if(!button||!current||!current.contains(button))return;
    var i=Number(button.hasAttribute("data-mp-tenet")?button.dataset.mpTenet:button.dataset.mpRow);
    choose(i,true);
  });
  document.addEventListener("pointerover",function(ev){
    var button=ev.target&&ev.target.closest&&ev.target.closest("[data-mp-tenet],[data-mp-row]");
    if(!button||!current||!current.contains(button)||button.contains(ev.relatedTarget))return;
    hovered=Number(button.hasAttribute("data-mp-tenet")?button.dataset.mpTenet:button.dataset.mpRow);
    highlight();
  });
  document.addEventListener("pointerout",function(ev){
    var button=ev.target&&ev.target.closest&&ev.target.closest("[data-mp-tenet],[data-mp-row]");
    if(!button||!current||!current.contains(button)||button.contains(ev.relatedTarget))return;
    hovered=-1;highlight();
  });
  document.addEventListener("focusin",function(ev){
    var button=ev.target&&ev.target.closest&&ev.target.closest("[data-mp-tenet],[data-mp-row]");
    if(!button||!current||!current.contains(button))return;
    hovered=Number(button.hasAttribute("data-mp-tenet")?button.dataset.mpTenet:button.dataset.mpRow);
    highlight();
  });
  document.addEventListener("focusout",function(ev){
    var button=ev.target&&ev.target.closest&&ev.target.closest("[data-mp-tenet],[data-mp-row]");
    if(!button||!current||!current.contains(button))return;
    hovered=-1;highlight();
  });
  install();
})();
